@lru_cache(None)
def _cursor():
    s = 4
    c = Image.new("RGBA", (36 * s, 50 * s), (0, 0, 0, 0))
    pts = [(2, 2), (2, 38), (11, 30), (17, 44), (23, 41), (17, 28), (29, 28)]
    ImageDraw.Draw(c).polygon([(px * s, py * s) for px, py in pts], fill=(255, 255, 255, 255), outline=(10, 10, 10, 255),
                              width=2 * s)
    return c.resize((36, 50), Image.LANCZOS)


def cursor(img, xy, click=None, t=0.0, alpha=1.0):
    """Arrow cursor at xy; click: time of a click, drawn as an expanding ring."""
    if alpha <= 0:
        return
    if click is not None and 0 <= t - click < 0.6:
        p = (t - click) / 0.6
        r = 14 + 40 * ease_out(p)
        layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
        ImageDraw.Draw(layer).ellipse((xy[0] - r, xy[1] - r, xy[0] + r, xy[1] + r), outline=(*CYAN, int(255 * (1 - p))),
                                      width=5)
        img.paste(layer, (0, 0), layer)
    press = 0.85 if click is not None and 0 <= t - click < 0.15 else 1.0
    c = _cursor()
    if press != 1.0:
        c = c.resize((int(c.width * press), int(c.height * press)), Image.LANCZOS)
    paste_alpha(img, c, (xy[0] - 2, xy[1] - 2), alpha)


def path(t, pts):
    """Cursor position along keyframes [(time, x, y)], eased between them."""
    if t <= pts[0][0]:
        return pts[0][1:]
    for (t0, x0, y0), (t1, x1, y1) in zip(pts, pts[1:]):
        if t <= t1:
            p = ease_io(win(t, t0, t1))
            return lerp(x0, x1, p), lerp(y0, y1, p)
    return pts[-1][1:]


def ring(img, box, t, start, color=CYAN, width=4, out=None):
    """Highlight box that draws itself."""
    p = ease_out(win(t, start, start + 0.5)) * (1 - (win(t, out, out + 0.3) if out is not None else 0))
    if p <= 0:
        return
    x0, y0, x1, y1 = box
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    grow = (1 - p) * 20
    d.rounded_rectangle((x0 - grow, y0 - grow, x1 + grow, y1 + grow), 12, outline=(*color, int(255 * p)), width=width)
    img.paste(layer, (0, 0), layer)


