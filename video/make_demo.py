def browser(img, src, rect, cam=(0.5, 0.5, 1.0), alpha=1.0, url=URL, scale=1.0, dy=0.0, src2=None, mix=0.0):
    """Draw a browser window showing src through camera (cx, cy, zoom); src2/mix crossfade to another page."""
    x, y, w, h = rect
    if scale != 1.0:
        cxr, cyr = x + w / 2, y + h / 2
        w, h = int(w * scale), int(h * scale)
        x, y = cxr - w / 2, cyr - h / 2
    y += dy
    w, h = int(w), int(h)
    bar = 44
    sh, pad = shadow(w, h, 18)
    layer = Image.new("RGBA", (w, h), (*PANEL, 255))
    d = ImageDraw.Draw(layer)
    d.rectangle((0, 0, w, bar), fill=(20, 32, 58, 255))
    for i, c in enumerate([(255, 95, 87), (254, 188, 46), (40, 200, 64)]):
        d.ellipse((18 + i * 22, bar / 2 - 6, 30 + i * 22, bar / 2 + 6), fill=(*c, 255))
    d.rounded_rectangle((w / 2 - 260, 9, w / 2 + 260, bar - 9), 13, fill=(10, 18, 36, 255))
    d.text((w / 2, bar / 2), url, font=font(MED, 18), fill=(*MUTED, 255), anchor="mm")
    content = view(src, *cam, w, h - bar)
    if src2 is not None and mix > 0:
        content = Image.blend(content, view(src2, *cam, w, h - bar), min(mix, 1.0))
    layer.paste(content, (0, bar))
    layer.putalpha(rounded_mask(w, h, 18))
    shl = Image.new("RGBA", sh.size, (0, 0, 0, 0))
    shl.putalpha(sh.point(lambda v: int(v * alpha)))
    img.paste((0, 0, 0), (int(x - pad), int(y - pad)), shl)
    paste_alpha(img, layer, (x, y), alpha)
    return x, y + bar, w, h - bar


def to_screen(rect, cam, src, px, py):
    """Pixel (px, py) of the screenshot -> canvas position inside a browser content rect."""
    x, y, w, h = rect
    cx, cy, zoom = cam
    sc = max(w / src.width, h / src.height) * zoom
    sw, sh = min(w / sc, src.width), min(h / sc, src.height)
    x0 = max(min(max(cx * src.width - sw / 2, 0), src.width - sw), 0)
    y0 = max(min(max(cy * src.height - sh / 2, 0), src.height - sh), 0)
    return x + (px - x0) / sw * w, y + (py - y0) / sh * h


