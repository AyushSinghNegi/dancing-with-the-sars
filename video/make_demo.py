def s_cloud(t, dur, captions=False, cues=None):
    img = bg(t)
    tiles = cloud_tiles()
    dates = ["3 Jul", "4 Jul", "5 Jul", "6 Jul", "7 Jul", "8 Jul"]
    sensors = ["Terra", "Aqua", "Suomi NPP", "NOAA-20"]
    tw, th, gap = 190, 148, 12
    gx, gy = 600, 230
    zoom = 1 + 0.04 * ease(win(t, 0, dur))
    layer = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    n_seen = 0
    order = []
    for r in range(4):
        for c in range(6):
            order.append((r, c))
    order.sort(key=lambda rc: rc[0] + rc[1] * 0.9)
    for k, (r, c) in enumerate(order):
        st = 0.25 + k * 0.07
        p = ease_out(win(t, st, st + 0.35))
        if p <= 0:
            continue
        x = gx + c * (tw + gap)
        y = gy + r * (th + gap)
        tile = tiles[(r, c + 1)]
        arr = np.asarray(tile)
        missing = arr.mean() < 40 or (arr.mean(2) < 15).mean() > 0.35
        if missing:
            cell = Image.new("RGB", (tw, th), (18, 24, 36))
            dd = ImageDraw.Draw(cell)
            for i in range(-th, tw, 16):
                dd.line((i, th, i + th, 0), fill=(28, 36, 52), width=4)
            dd.text((tw / 2, th / 2), "no image", font=font(MED, 22), fill=MUTED, anchor="mm")
        else:
            cell = tile.resize((tw, th), Image.BICUBIC)
            n_seen += 1 if p > 0.5 else 0
        cell = cell.convert("RGBA")
        cell.putalpha(rounded_mask(tw, th, 10))
        s_ = 0.85 + 0.15 * p
        cw, ch = int(tw * s_), int(th * s_)
        cell = cell.resize((cw, ch), Image.LANCZOS)
        a = cell.getchannel("A").point(lambda v: int(v * p))
        cell.putalpha(a)
        layer.paste(cell, (int(x + (tw - cw) / 2), int(y + (th - ch) / 2)), cell)
    for c, ds in enumerate(dates):
        d.text((gx + c * (tw + gap) + tw / 2, gy - 26), ds, font=font(MED, 24), fill=(*MUTED, int(255 * win(t, 0.1, 0.5))),
               anchor="mm")
    for r, sn in enumerate(sensors):
        d.text((gx - 20, gy + r * (th + gap) + th / 2), sn, font=font(MED, 22),
               fill=(*MUTED, int(255 * win(t, 0.1, 0.5))), anchor="rm")
    if zoom != 1:
        layer = layer.resize((int(W * zoom), int(H * zoom)), Image.BICUBIC).crop(
            (int(W * (zoom - 1) / 2), int(H * (zoom - 1) / 2), int(W * (zoom - 1) / 2) + W, int(H * (zoom - 1) / 2) + H))
    img.paste(layer, (0, 0), layer)
    # counter
    cnt = min(22, n_seen)
    text(img, (96, 330), f"{cnt}", font(HEAD, 220), fill=WHITE, alpha=win(t, 0.3, 0.6))
    text(img, (100, 570), "of 22 satellite", font(SEMI, 34), fill=INK, alpha=win(t, 0.5, 0.8))
    text(img, (100, 614), "photos showed", font(SEMI, 34), fill=INK, alpha=win(t, 0.5, 0.8))
    text(img, (100, 658), "only cloud", font(SEMI, 34), fill=CYAN, alpha=win(t, 0.6, 0.9))
    kicker(img, t, "Pune, India: 3 to 8 July 2026, floods and landslides", start=0.05)
    text(img, (gx, gy + 4 * (th + gap) + 6), "NASA Worldview daily images from four satellites", font(REG, 22), fill=MUTED,
         alpha=win(t, 1.0, 1.4))
    # cloud whiteout into the radar
    wo = win(t, dur - 0.55, dur)
    if wo > 0:
        img = Image.blend(img, Image.new("RGB", (W, H), (236, 240, 244)), ease(wo) * 0.85)
    return img


