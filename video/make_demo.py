def vo_plan(which):
    """Lay the scenes out around the recorded voice. Returns scenes [(name, fn, dur)], words [(text, t0, t1)],
    sentence placements [(file, start, tempo)], caption chunks [(t0, t1, [word indices])] and the tempo."""
    from functools import partial
    d = json.load(open(VO_DIR / f"{which}_vo.json"))
    sents = d["sentences"]
    order = []
    for x in sents:
        if x["scene"] not in order:
            order.append(x["scene"])
    if "end" not in order:
        order.append("end")
    GAP, TAIL = 0.3, (0.22 if which in LIMIT else 0.3)

    def lead(sc):
        return 0.35 if sc == order[0] else (0.12 if which == "short" else 0.3)

    def durs(tempo):
        out = {}
        for sc in order:
            ss = [x for x in sents if x["scene"] == sc]
            speech = sum(x["dur"] for x in ss) / tempo + GAP * max(0, len(ss) - 1)
            out[sc] = max(MIN_DUR[sc], lead(sc) + speech + TAIL) if ss else MIN_DUR[sc]
        return out
    tempo = 1.0
    if which in LIMIT:
        while sum(durs(tempo).values()) > LIMIT[which] and tempo < 1.08:
            tempo = round(tempo + 0.005, 3)
        D = durs(tempo)
        D["end"] += max(0.0, LIMIT[which] - sum(D.values()))
    else:
        D = durs(tempo)
        D["end"] = max(D["end"], 4.5)
    words, places, sent_words, t = [], [], [], 0.0
    starts = {}
    for sc in order:
        starts[sc] = t
        cur = t + lead(sc)
        for x in [x for x in sents if x["scene"] == sc]:
            places.append((x["file"], cur))
            idx = []
            for w, a, b in x["words"]:
                idx.append(len(words))
                words.append((w, cur + a / tempo, cur + b / tempo))
            sent_words.append(idx)
            cur += x["dur"] / tempo + GAP
        t += D[sc]

    def at(sc, word, nth=0, before=0.0):
        """Seconds into scene sc where `word` is spoken (nth time in that scene)."""
        hits = [w for w in words if starts[sc] <= w[1] < starts[sc] + D[sc] and
                re.sub(r"[^\w²]", "", w[0].lower()) == word]
        return max(0.1, hits[nth][1] - starts[sc] - before) if len(hits) > nth else None

    cues = {sc: {} for sc in order}

    def put(sc, key, val):
        if val is not None:
            cues[sc][key] = val
    put("radar", "wipe", at("radar", "nasa", 0, -0.1))
    put("radar", "rise", at("radar", "water"))
    put("radar", "zones", at("radar", "50"))
    if which == "long":
        put("app", "click", at("app", "tour", 0, -0.2))
        put("map", "switch", at("map", "explore", 0, 0.3))
        a1, a2, a3 = at("checks", "independent"), at("checks", "35"), at("checks", "reported")
        if None not in (a1, a2, a3):
            cues["checks"]["cards"] = [a1, a2, a2 + 0.6, a3]
        put("field", "click", at("field", "radar", 0, 0.1))
        put("field", "phones", at("field", "printable"))
        put("field", "chips", at("field", "english", 0, 0.2))
        put("place", "phone", at("place", "lonavala", 0, 0.4))
        put("method", "mix", at("method", "everything", 0, 0.2))
    else:
        put("field", "chips", at("field", "four", 0, 0.2))
    scenes = [(sc, partial(scene_fn(sc), cues=cues[sc]), D[sc]) for sc in order]
    # caption chunks: up to ~44 characters, shown from just before their first word until the next chunk
    chunks = []
    for idx in sent_words:   # balanced lines of at most ~44 characters, breaking after punctuation where possible
        parts, cur = [], []
        for i in idx:
            cur.append(i)
            if words[i][0].endswith((".", ":", "?", ";")):
                parts.append(cur)
                cur = []
        if cur:
            parts.append(cur)
        for part in parts:
            n_ch = len(" ".join(words[i][0] for i in part))
            n = max(1, -(-n_ch // 44))
            target = n_ch / n
            line, ln = [], 0
            for i in part:
                wl = len(words[i][0]) + 1
                if line and ln + wl / 2 > target and len(chunks) >= 0 and (n_ch - ln) > 0 and \
                        sum(1 for _ in line) > 0 and ln >= target * 0.75:
                    chunks.append(line)
                    line, ln = [], 0
                line.append(i)
                ln += wl
            if line:
                chunks.append(line)
    timed = []
    for k, ch in enumerate(chunks):
        a = words[ch[0]][1] - 0.12
        b = words[ch[-1]][2] + 0.45
        timed.append([a, b, ch, True, True])
    for k in range(len(timed) - 1):   # back-to-back lines switch without fading and never overlap
        if timed[k + 1][0] - timed[k][1] < 0.35:
            timed[k][1] = timed[k + 1][0]
            timed[k][4] = timed[k + 1][3] = False
    timed = [tuple(x) for x in timed]
    return scenes, words, places, timed, tempo, D


def karaoke(img, T, words, chunks):
    """Caption line at the bottom; the word being spoken lights up, spoken words are white, the rest are dim."""
    for a, b, ch, fin, fout in chunks:
        if not ((a - 0.15 if fin else a) <= T < (b + 0.15 if fout else b)):
            continue
        al = (ease(win(T, a - 0.15, a)) if fin else 1.0) * ((1 - ease(win(T, b, b + 0.15))) if fout else 1.0)
        if al <= 0:
            continue
        f = font(SEMI, 42)
        layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
        d = ImageDraw.Draw(layer)
        texts = [words[i][0] for i in ch]
        sp = d.textlength(" ", font=f)
        wl = [d.textlength(x, font=f) for x in texts]
        tw = sum(wl) + sp * (len(texts) - 1)
        x0, y1 = (W - tw) / 2, H - 46
        y0 = y1 - 74
        d.rounded_rectangle((x0 - 30, y0, x0 + tw + 30, y1), 16, fill=(4, 8, 16, int(205 * al)))
        x = x0
        spoken = [i for i in ch if words[i][1] <= T]
        cur = spoken[-1] if spoken and T < words[spoken[-1]][2] + 0.25 else None
        for i, tx, w_ in zip(ch, texts, wl):
            if i == cur:
                d.rounded_rectangle((x - 8, y0 + 12, x + w_ + 8, y1 - 12), 10, fill=(*CYAN, int(235 * al)))
                col, a_ = NAVY, 1.0
            elif words[i][1] <= T:
                col, a_ = WHITE, 1.0
            else:
                col, a_ = (205, 214, 228), 0.5
            d.text((x, (y0 + y1) / 2), tx, font=f, fill=(*col, int(255 * al * a_)), anchor="lm")
            x += w_ + sp
        img.paste(layer, (0, 0), layer)


def karaoke_srt(words, chunks, path_):
    def ts(x):
        ms = int(round(max(0, x) * 1000))
        return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"
    path_.write_text("".join(f"{k}\n{ts(a)} --> {ts(b)}\n{' '.join(words[i][0] for i in ch)}\n\n"
                             for k, (a, b, ch, _, _) in enumerate(chunks, 1)))
    print(path_)


def timeline(scenes):
    t, out = 0.0, []
    for name, fn, dur in scenes:
        out.append((name, fn, t, dur))
        t += dur
    return out, t


def frame_at(scenes, T, captions=None, kara=None):
    tl, total = timeline(scenes)
    for i, (name, fn, t0, dur) in enumerate(tl):
        if T < t0 + dur or i == len(tl) - 1:
            img = fn(T - t0, dur)
            if i + 1 < len(tl) and T > t0 + dur - XF:
                nxt = tl[i + 1]
                p = ease(win(T, t0 + dur - XF, t0 + dur))
                img = Image.blend(img, nxt[1](T - nxt[2], nxt[3]), p)
            if captions:
                for (a, b, s) in captions:
                    if a - 0.3 <= T <= b + 0.3:
                        caption(img, T, s, a, b)
            if kara:
                karaoke(img, T, *kara)
            return img
    raise ValueError(T)


def render(scenes, out_path, captions=None, kara=None):
    _, total = timeline(scenes)
    n = int(round(total * FPS))
    tmp = out_path.with_suffix(".part.mp4")
    cmd = ["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}", "-r", str(FPS),
           "-i", "-", "-f", "lavfi", "-i", "anullsrc=r=48000:cl=stereo", "-shortest", "-c:v", "libx264", "-preset",
           "veryfast", "-crf", "17", "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "128k", "-movflags", "+faststart",
           str(tmp)]
    pr = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    for i in range(n):
        pr.stdin.write(frame_at(scenes, i / FPS, captions, kara).tobytes())
        if i % 60 == 0:
            print(f"{i}/{n}", flush=True)
    pr.stdin.close()
    if pr.wait() == 0:
        tmp.rename(out_path)
        print(out_path, total, "s")


def vo_script(scenes, path_):
    tl, total = timeline(scenes)
    lines = [f"MonsoonLens, 30-second demo: voice-over script ({total:.1f} s)", "",
             "Read at a calm pace, about 2.4 words a second. Times are where each line starts.", ""]
    for name, fn, t0, dur in tl:
        lines.append(f"{int(t0 // 60)}:{t0 % 60:05.2f}  [{name}, {dur:.1f} s]  {VO[name]}")
    words = sum(len(v.split()) for v in VO.values())
    lines += ["", f"{words} words."]
    path_.write_text("\n".join(lines) + "\n")
    print(path_)


