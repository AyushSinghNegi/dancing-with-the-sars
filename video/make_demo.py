@lru_cache(None)
def rounded_mask(w, h, r):
    m = Image.new("L", (w * 2, h * 2), 0)
    ImageDraw.Draw(m).rounded_rectangle((0, 0, w * 2 - 1, h * 2 - 1), r * 2, fill=255)
    return m.resize((w, h), Image.LANCZOS)


@lru_cache(None)
def shadow(w, h, r, blur=40, alpha=150):
    pad = blur * 2
    s = Image.new("L", (w + pad * 2, h + pad * 2), 0)
    ImageDraw.Draw(s).rounded_rectangle((pad, pad + 14, pad + w, pad + h + 14), r, fill=alpha)
    return s.filter(ImageFilter.GaussianBlur(blur)), pad


def paste_alpha(img, layer, xy, alpha=1.0):
    if alpha <= 0:
        return
    if alpha < 1:
        a = layer.getchannel("A").point(lambda v: int(v * alpha))
        layer = layer.copy()
        layer.putalpha(a)
    img.paste(layer, (int(round(xy[0])), int(round(xy[1]))), layer)


def view(src, cx, cy, zoom, w, h):
    """Crop of src around (cx, cy) (fractions) that covers w x h at zoom 1 (and 1/zoom of that at higher zoom)."""
    sc = max(w / src.width, h / src.height) * zoom
    sw, sh = min(w / sc, src.width), min(h / sc, src.height)
    x0 = max(min(max(cx * src.width - sw / 2, 0), src.width - sw), 0)
    y0 = max(min(max(cy * src.height - sh / 2, 0), src.height - sh), 0)
    return src.resize((w, h), Image.BICUBIC, box=(x0, y0, x0 + sw, y0 + sh))


def bg(t=0.0):
    """Navy background with a slow radial glow."""
    return _bg_cached(int(t * 6) % 360).copy()


@lru_cache(None)
def _bg_cached(k):
    img = Image.new("RGB", (W, H), NAVY)
    g = Image.new("L", (W // 4, H // 4), 0)
    d = ImageDraw.Draw(g)
    ang = math.radians(k)
    cx, cy = W / 8 + math.cos(ang) * 60, H / 8 + math.sin(ang) * 30
    d.ellipse((cx - 260, cy - 160, cx + 260, cy + 160), fill=90)
    g = g.filter(ImageFilter.GaussianBlur(70)).resize((W, H), Image.BICUBIC)
    glow = Image.new("RGB", (W, H), (20, 52, 110))
    img.paste(glow, (0, 0), g)
    return img


# ------------------------------------------------------------------ text
def text(img, xy, s, f, fill=WHITE, alpha=1.0, anchor="la", stroke=0):
    if alpha <= 0:
        return
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    ImageDraw.Draw(layer).text(xy, s, font=f, fill=(*fill, int(255 * alpha)), anchor=anchor,
                               stroke_width=stroke, stroke_fill=(*NAVY, int(200 * alpha)))
    img.paste(layer, (0, 0), layer)


HEADLINES = {"on": True}   # the captioned walkthrough turns the kinetic headlines off: captions carry the words


def headline(img, t, lines, x=96, y=820, size=76, color=WHITE, start=0.0, sub=None, sub_color=MUTED, scrim=True,
             out=None):
    """Kinetic headline: each word rises and fades in. lines: list of strings. out: time it fades away."""
    if not HEADLINES["on"]:
        return
    f = font(HEAD, size)
    a_out = 1 - win(t, out, out + 0.35) if out is not None else 1
    if a_out <= 0:
        return
    if scrim:
        sc = _scrim()
        paste_alpha(img, sc, (0, 0), min(1, win(t, start - 0.1, start + 0.3)) * a_out)
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    k = 0
    lh = int(size * 1.08)
    for li, ln in enumerate(lines):
        cx = x
        for w_ in ln.split(" "):
            p = ease_out(win(t, start + k * 0.055, start + k * 0.055 + 0.45))
            dy = (1 - p) * 34
            col = color
            if w_.startswith("*"):
                w_ = w_[1:]
                col = CYAN
            d.text((cx, y + li * lh + dy), w_, font=f, fill=(*col, int(255 * p * a_out)))
            cx += d.textlength(w_ + " ", font=f)
            k += 1
    if sub:
        p = ease_out(win(t, start + k * 0.055 + 0.15, start + k * 0.055 + 0.6))
        d.text((x, y + len(lines) * lh + 14 + (1 - p) * 20), sub, font=font(MED, 30),
               fill=(*sub_color, int(255 * p * a_out)))
    img.paste(layer, (0, 0), layer)


@lru_cache(None)
def _scrim():
    a = np.zeros((H, W), np.float32)
    ys = np.linspace(0, 1, H)[:, None]
    a[:] = np.clip((ys - 0.45) / 0.55, 0, 1) ** 1.6 * 235
    s = Image.new("RGBA", (W, H), (*NAVY, 0))
    s.putalpha(Image.fromarray(a.astype(np.uint8)))
    return s


def kicker(img, t, s, x=96, y=96, start=0.0, color=CYAN, out=None):
    p = ease_out(win(t, start, start + 0.4)) * (1 - (win(t, out, out + 0.3) if out is not None else 0))
    if p <= 0:
        return
    f = font(SEMI, 28)
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    tw = d.textlength(s, font=f)
    d.rounded_rectangle((x, y, x + (tw + 44) * p, y + 50), 25, fill=(*NAVY2, int(230 * p)), outline=(*color, int(255 * p)),
                        width=2)
    d.ellipse((x + 16, y + 19, x + 28, y + 31), fill=(*color, int(255 * p)))
    if p > 0.6:
        d.text((x + 38, y + 25), s, font=f, fill=(*WHITE, int(255 * (p - 0.6) / 0.4)), anchor="lm")
    img.paste(layer, (0, 0), layer)


def caption(img, t, s, start, end):
    """Burnt-in caption for the long walkthrough (bottom centre, readable on a phone)."""
    a = ease(win(t, start, start + 0.25)) * (1 - ease(win(t, end - 0.25, end)))
    if a <= 0 or not s:
        return
    f = font(MED, 38)
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    words, lines, cur = s.split(), [], ""
    for w_ in words:
        tr = (cur + " " + w_).strip()
        if d.textlength(tr, font=f) <= 1500:
            cur = tr
        else:
            lines.append(cur)
            cur = w_
    lines.append(cur)
    lh = 52
    tw = max(d.textlength(l, font=f) for l in lines)
    y1 = H - 40
    y0 = y1 - lh * len(lines) - 26
    d.rounded_rectangle(((W - tw) / 2 - 30, y0, (W + tw) / 2 + 30, y1), 14, fill=(4, 8, 16, int(215 * a)))
    for i, l in enumerate(lines):
        d.text((W / 2, y0 + 13 + i * lh), l, font=f, fill=(*WHITE, int(255 * a)), anchor="ma")
    img.paste(layer, (0, 0), layer)


