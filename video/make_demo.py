@lru_cache(None)
def radar_assets():
    hb = Image.open(LAYERS / "hh_before.webp").convert("RGBA")
    ha = Image.open(LAYERS / "hh_after.webp").convert("RGBA")
    geo = Geo(BOUNDS, ha.size)
    side = 1000   # square map area on canvas, height
    sc = side / ha.size[1]
    size = (round(ha.size[0] * sc), side)

    def prep(im, dim=0.62):
        base = Image.new("RGB", im.size, NAVY)
        base.paste(im.convert("RGB"), (0, 0), im)
        arr = np.asarray(base).astype(np.float32) * dim
        return Image.fromarray(arr.clip(0, 255).astype(np.uint8)).resize(size, Image.LANCZOS)

    b, a = prep(hb), prep(ha)
    perm = tint(Image.open(LAYERS / "permanent.png"), (150, 190, 235), 120).resize(size, Image.LANCZOS)
    rise = tint(Image.open(LAYERS / "rise.png"), CYAN, 255, grow=2).resize(size, Image.LANCZOS)
    glow = rise.filter(ImageFilter.GaussianBlur(6))
    return b, a, perm, rise, glow, geo, sc, size


def s_radar(t, dur, captions=False, cues=None):
    c = cues or {}
    w0, r0, z0 = c.get("wipe", 0.9), c.get("rise", 2.1), c.get("zones", 2.6)
    img = bg(t)
    b, a, perm, rise, glow, geo, sc, size = radar_assets()
    mx, my = W - size[0] - 60, 40
    zoom = 1.0 + 0.06 * ease(win(t, 0, dur))
    # the wipe: before -> after
    wp = ease_io(win(t, w0, w0 + 1.3))
    base = b.copy()
    cut = int(size[0] * wp)
    if cut > 0:
        base.paste(a.crop((0, 0, cut, size[1])), (0, 0))
    base = base.convert("RGBA")
    base.alpha_composite(perm)
    ra = ease(win(t, r0, r0 + 0.7))
    if ra > 0:
        g = glow.copy()
        g.putalpha(g.getchannel("A").point(lambda v: int(v * ra * 0.9)))
        base.alpha_composite(g)
        r = rise.copy()
        r.putalpha(r.getchannel("A").point(lambda v: int(v * ra)))
        base.alpha_composite(r)
    d = ImageDraw.Draw(base)
    if 0 < wp < 1:
        d.line((cut, 0, cut, size[1]), fill=(*CYAN, 255), width=4)
    zs = sorted(ZONES, key=lambda f: -f["properties"].get("score", 0))
    for k, f in enumerate(zs):
        p = ease_out(win(t, z0 + k * 0.022, z0 + k * 0.022 + 0.3))
        if p <= 0:
            continue
        pr = f["properties"]
