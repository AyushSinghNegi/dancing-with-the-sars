"""Write content/validation.md: the plain validation table for the app, slides and project page (U5).

Results come from data/derived/validation.csv (RSN's pipeline.validate); place names and source
links come from data/reference/events.geojson. Nothing is typed by hand, so re-run this after
every new validation run:

  python content/build_validation_table.py
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
TYPE_WORDS = {"landslide": "Landslide", "river_overflow": "River overflow", "waterlogging": "Waterlogging",
              "flood": "Flood", "road_closure": "Road closure"}
DETECTED = {"hit": "Yes", "miss": "No"}


def _date(iso: str) -> str:
    return f"{int(iso[8:10])} {MONTHS[int(iso[5:7]) - 1]} {iso[:4]}" if iso else "not available"


def build() -> str:
    rows = list(csv.DictReader(open(ROOT / "data/derived/validation.csv", encoding="utf-8")))
    events = {f["properties"]["id"]: f["properties"]
              for f in json.loads((ROOT / "data/reference/events.geojson").read_text(encoding="utf-8"))["features"]}
    missing = [r["id"] for r in rows if r["id"] not in events] + [i for i in events if i not in {r["id"] for r in rows}]
    if missing:
        raise SystemExit(f"validation.csv and events.geojson disagree on: {missing}. Re-run pipeline.validate.")

    def count(kind, result=None):
        is_slide = lambda r: r["type"] == "landslide"
        pick = [r for r in rows if is_slide(r) == (kind == "slide") and r["observable"] == "yes"]
        return len(pick) if result is None else sum(r["result"] == result for r in pick)

    out = ["# Validation: reported events against the radar map", "",
           "<!-- Generated by content/build_validation_table.py from data/derived/validation.csv and",
           "     data/reference/events.geojson. Do not edit by hand; re-run the script. -->", "",
           f"We collected {len(rows)} reported events, each with a linked source. "
           f"Of the {count('flood')} reported floods that radar could observe, {count('flood', 'hit')} had a "
           f"detection nearby; of the {count('slide')} landslides, {count('slide', 'hit')}.", "",
           "\"Detected\" means a radar detection lies within the distance the report's location allows. "
           "\"Could not check\" means the radar had no fair chance: the reason is given.", "",
           "| ID | Event | Type | Date | Detected | Reason if missed or not checked | Source |",
           "|---|---|---|---|---|---|---|"]
    for r in rows:
        e = events[r["id"]]
        reason = r["reason"].strip()
        reason = reason[:1].upper() + reason[1:] if reason else ""
        out.append(f"| {r['id']} | {e['place']} | {TYPE_WORDS.get(r['type'], r['type'])} | {_date(r['date'])} | "
                   f"{DETECTED.get(r['result'], 'Could not check')} | {reason} | [{e['source_name']}]({e['source_url']}) |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    target = ROOT / "content" / "validation.md"
    target.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {target.relative_to(ROOT)}")
